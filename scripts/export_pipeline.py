"""Freeze the chosen version into a standalone deliverable.

    python export_pipeline.py --workdir W                 # best valid version
    python export_pipeline.py --workdir W --version v4

1. Scores the version once on the held-out split (never used while exploring).
2. Processes ALL input images into W/deliverable/cleaned/ (originals untouched).
3. Writes W/deliverable/: pipeline.json, ops.py, preprocess.py (CLI + importable
   preprocess(img) for feeding a model), report.json, custom modules if any.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import list_images, load_goal, proxy_score, read_jsonl, run_eval_cmd, select  # noqa: E402
from experiment import gain, keep_rate_of, process_split, status  # noqa: E402

PREPROCESS_PY = '''"""Generated by cv-preprocess-explore. Apply the frozen pipeline.

CLI:     python preprocess.py --input <dir> --output <dir>
Python:  from preprocess import preprocess; clean = preprocess(img)  # BGR/gray uint8
"""
import argparse, json, sys
from pathlib import Path

import cv2

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from ops import IMAGE_EXTS, apply_pipeline, load_image, save_image  # noqa: E402

PIPE = json.loads((HERE / "pipeline.json").read_text(encoding="utf-8"))


def preprocess(img):
    out = apply_pipeline(img, PIPE["steps"], HERE)
    mode = PIPE["output"]["mode"]
    if mode == "gray" and out.ndim == 3:
        out = cv2.cvtColor(out, cv2.COLOR_BGR2GRAY)
    elif mode == "color" and out.ndim == 2:
        out = cv2.cvtColor(out, cv2.COLOR_GRAY2BGR)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--output", required=True)
    a = ap.parse_args()
    src, dst = Path(a.input), Path(a.output)
    ext = "." + PIPE["output"]["format"].lstrip(".")
    n = bad = 0
    for f in sorted(p for p in src.rglob("*") if p.suffix.lower() in IMAGE_EXTS):
        img = load_image(f)
        if img is None:
            bad += 1
            print(f"skip unreadable: {f}")
            continue
        save_image(dst / f.relative_to(src).with_suffix(ext), preprocess(img))
        n += 1
    print(f"done: {n} images -> {dst}  ({bad} unreadable)")


if __name__ == "__main__":
    main()
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workdir", required=True)
    ap.add_argument("--version")
    ap.add_argument("--force", action="store_true", help="re-score holdout (only with user approval)")
    a = ap.parse_args()
    work = Path(a.workdir).resolve()
    goal = load_goal(work)
    info = status(work, goal, quiet=True)
    name = a.version or info["best"]
    if not name:
        sys.exit("no valid version to export")
    runs = {r["name"]: r for r in read_jsonl(work / "runs.jsonl") if r["split"] == "explore"}
    if name not in runs:
        sys.exit(f"unknown version {name}")
    scored = [r["name"] for r in read_jsonl(work / "runs.jsonl") if r["split"] == "holdout"]
    if scored and not a.force:
        sys.exit(f"holdout already scored for {scored}. The holdout is used once: exporting again after seeing it "
                 "turns it into tuning data. --force only if the user explicitly approved.")
    explore = runs[name]
    cfg = json.loads((work / "runs" / name / "config.json").read_text(encoding="utf-8"))
    steps, filt = cfg.get("steps", []), cfg.get("filter", {})
    root = Path(goal["input_dir"])
    all_files = list_images(root)
    out = work / "deliverable"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    # 1) holdout, scored once
    hold = select(all_files, root, "holdout", goal["holdout_fraction"])
    holdout = None
    if hold:
        hdir = work / "runs" / f"{name}__holdout"
        if hdir.exists():
            shutil.rmtree(hdir)
        per, rej, err, _, ms = process_split(goal, steps, filt, hold, root, hdir / "images", work, save=True)
        proxy, rates = proxy_score(per, goal["checks"])
        ev = None
        if goal["eval_cmd"]:
            lst = hdir / "files.txt"
            lst.write_text("\n".join(str(p) for p in sorted((hdir / "images").rglob("*")) if p.is_file()), encoding="utf-8")
            ev = run_eval_cmd(goal["eval_cmd"], root, hdir / "images", lst, goal["eval_timeout_s"])
        score = ev["score"] if goal["primary"] == "eval_cmd" else proxy
        holdout = {"n": len(hold), "score": score, "proxy_score": proxy, "eval": ev, "pass_rates": rates,
                   "keep_rate": keep_rate_of(per, rej, len(hold)), "errors": err[:20]}
        # baseline on holdout, for an honest before/after
        bper, _, _, _, _ = process_split(goal, [], {}, hold, root, hdir / "_base", work, save=bool(goal["eval_cmd"]))
        bproxy, _ = proxy_score(bper, goal["checks"])
        bev = None
        if goal["eval_cmd"]:
            blst = hdir / "base_files.txt"
            blst.write_text("\n".join(str(p) for p in sorted((hdir / "_base").rglob("*")) if p.is_file()), encoding="utf-8")
            bev = run_eval_cmd(goal["eval_cmd"], root, hdir / "_base", blst, goal["eval_timeout_s"])
        holdout["baseline_score"] = bev["score"] if goal["primary"] == "eval_cmd" else bproxy
        with open(work / "runs.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps({"name": name, "split": "holdout", "valid": True,
                                 "time": dt.datetime.now().isoformat(timespec="seconds"), **holdout},
                                ensure_ascii=False) + "\n")

    # 2) clean everything
    per, rej, err, _, ms = process_split(goal, steps, filt, all_files, root, out / "cleaned", work, save=True)

    # 3) package
    here = Path(__file__).resolve().parent
    shutil.copy(here / "ops.py", out / "ops.py")
    (out / "preprocess.py").write_text(PREPROCESS_PY, encoding="utf-8")
    for st in steps:
        if st.get("op") == "custom":
            dst = out / st["module"]
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(work / st["module"], dst)
    (out / "pipeline.json").write_text(json.dumps(
        {"version": name, "steps": steps, "filter": filt, "output": goal["output"]},
        ensure_ascii=False, indent=2), encoding="utf-8")
    report = {
        "task": goal["task"],
        "version": name,
        "pipeline": steps,
        "filter": filt,
        "metric": "eval_cmd" if goal["primary"] == "eval_cmd" else "proxy (checks pass %)",
        "explore": {"n": explore["n"], "score": explore["score"], "baseline_score": info["baseline_score"],
                    "pass_rates": explore["pass_rates"]},
        "holdout": holdout,
        "all": {"n": len(all_files), "cleaned": len(per), "rejected": rej, "errors": err[:20], "ms_per_img": ms},
        "versions_tried": info["tried"],
        "stop_reason": info["stop"] or ["chosen manually"],
    }
    (out / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"exported {name} -> {out}")
    print(f"explore score {explore['score']} (baseline {info['baseline_score']})")
    if holdout:
        print(f"holdout score {holdout['score']} (baseline {holdout['baseline_score']}) n={holdout['n']}")
        eg = gain(explore["score"], info["baseline_score"], goal)
        hg = gain(holdout["score"], holdout["baseline_score"], goal)
        if eg is not None and eg > 0 and hg is not None and hg < 0.5 * eg:
            print(f"WARNING: holdout gain {hg} is under half the explore gain {eg} - likely overfit to explore images")
    else:
        print("holdout: none (fewer than 10 images or holdout_fraction=0)")
    print(f"cleaned {len(per)}/{len(all_files)}  rejected {len(rej)}  errors {len(err)}  {ms} ms/img")


if __name__ == "__main__":
    main()
